const fitStart=app.indexOf('function fitMapNodeText(');
const fitEnd=app.indexOf('function fitMapTexts(',fitStart);
assert.ok(fitStart>=0&&fitEnd>fitStart,'A função de autoajuste deve estar isolada e testável.');
const fitContext={};vm.createContext(fitContext);
vm.runInContext(`${app.slice(fitStart,fitEnd)};globalThis.__fit=fitMapNodeText;`,fitContext);
const textNode={style:{},dataset:{},clientHeight:120,clientWidth:260,get scrollHeight(){return Number.parseFloat(this.style.fontSize||'12')*10;},get scrollWidth(){return 100;}};
fitContext.__fit({querySelector:()=>textNode},{fontSize:22,fitText:true});
assert.ok(Number.parseFloat(textNode.style.fontSize)<=12,'O autoajuste deve diminuir a fonte até que o texto caiba.');
assert.equal(textNode.dataset.fitTextApplied,textNode.style.fontSize.replace('px',''));
assert.equal(textNode.style.fontSize,'12px');
const fixedText={style:{},dataset:{},clientHeight:120,clientWidth:260,get scrollHeight(){return Number.parseFloat(this.style.fontSize||'12')*10;},get scrollWidth(){return 100;}};
const fixedNode={fontSize:22,fitText:false};
fitContext.__fit({querySelector:()=>fixedText},fixedNode);
assert.equal(fixedText.style.fontSize,'22px','Sem autoajuste, o tamanho exato definido pela pessoa deve permanecer.');
assert.equal(fixedNode.fontSize,22,'O tamanho-base nunca deve ser sobrescrito pelo ajuste visual.');
assert.match(css, /max-height:none!important/, 'A imagem não pode ficar presa a um limite de altura antigo.');
assert.match(css, /\.map-node\[data-node-type=\"image\"\] \.map-image-frame/, 'A área da imagem precisa crescer junto do bloco.');
assert.match(css, /Dark themes: raise contrast/, 'Os temas escuros precisam de reforço de contraste em componentes antigos.');
const paletteStart=app.indexOf('function hexToHsl(');
const paletteEnd=app.indexOf('const QUICK_COLOR_SWATCHES',paletteStart);
assert.ok(paletteStart>=0&&paletteEnd>paletteStart,'As funções da paleta precisam estar disponíveis para teste.');
const paletteContext={};vm.createContext(paletteContext);
vm.runInContext(`${app.slice(paletteStart,paletteEnd)};globalThis.__palette={appPalette,contrastRatio,bestContrastingText};`,paletteContext);
for(const theme of ['light','dark','midnight']) for(const base of ['#000000','#ffffff','#808080','#ff0000','#00ff00','#0000ff','#ffcc00','#6db8eb','#aa66cc']){
  const palette=paletteContext.__palette.appPalette(base,theme);
  for(const entry of palette.entries){
    assert.ok(entry.contrast>=4.5,`A cor ${entry.color} da paleta ${theme} precisa ter contraste >= 4.5:1.`);
    assert.equal(entry.foreground,paletteContext.__palette.bestContrastingText(entry.color));
  }
}
